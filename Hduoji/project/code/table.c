// ==================== 参数定义 ====================
#define P_MAX           14.5f
#define P_MIN           2.7f
#define P_EXT_MAX       15.0f   // 扩展上限（防止外推过大）
#define P_EXT_MIN       2.0f    // 扩展下限
#define EXTRAP_LIMIT    1.5f

/**
 * @brief 纯高度控制的舵机PWM输出（使用一维表格）
 * @param p 高度值（范围：2.7 ~ 14.5）
 * @param pwm1 输出pwm1指针
 * @param pwm2 输出pwm2指针
 */
void servo_control_height(float p, int16* pwm1, int16* pwm2)
{
    // ========== 高度范围检查 ==========
    if (p > P_EXT_MAX || p < P_EXT_MIN) {
        *pwm1 = 10000;
        *pwm2 = 10000;
        return;
    }
    
    // ========== 计算外推系数 ==========
    float extrap = 1.0f;
    float p_clamped = p;
    
    if (p < P_MIN) {
        extrap = 1.0f + (p - P_MIN) / (P_MAX - P_MIN);
        if (extrap < 0) extrap = 0;
        if (extrap > EXTRAP_LIMIT) extrap = EXTRAP_LIMIT;
        p_clamped = P_MIN;
    }
    else if (p > P_MAX) {
        extrap = 1.0f + (p - P_MAX) / (P_MAX - P_MIN);
        if (extrap < 0) extrap = 0;
        if (extrap > EXTRAP_LIMIT) extrap = EXTRAP_LIMIT;
        p_clamped = P_MAX;
    }
    
    // ========== 计算表格索引 ==========
    float p_f = (p_clamped - P_MIN) / (P_MAX - P_MIN) * (P_TABLE_SIZE - 1);
    
    if (p_f < 0) p_f = 0;
    if (p_f >= P_TABLE_SIZE) p_f = P_TABLE_SIZE - 0.001f;
    
    int p0 = (int)p_f;
    int p1 = p0 + 1;
    if (p1 >= P_TABLE_SIZE) p1 = p0;
    
    float p_ratio = p_f - p0;
    
    // ========== 线性插值 pwm1 ==========
    float v1_0 = pwm1_height_table[p0];
    float v1_1 = pwm1_height_table[p1];
    float val1 = v1_0 * (1 - p_ratio) + v1_1 * p_ratio;
    *pwm1 = (int16)(val1 * extrap);
    
    // ========== 线性插值 pwm2 ==========
    float v2_0 = pwm2_height_table[p0];
    float v2_1 = pwm2_height_table[p1];
    float val2 = v2_0 * (1 - p_ratio) + v2_1 * p_ratio;
    *pwm2 = (int16)(val2 * extrap);
}

